"""
Summarises results/tabm_gns/ into summary.md, runs.csv and figures/.

  python -m experiments.tabm_gns.report [--results results/tabm_gns]
"""
from __future__ import annotations

import argparse
import csv
import json
import math
from collections import defaultdict
from pathlib import Path
from typing import Dict, List, Optional

import numpy as np

METHODS = ['mlp_large', 'mlp_gns', 'tabm_large', 'tabm_gns', 'tabm_gns_member']
LABEL = {'mlp_large': 'Large MLP (5×512)', 'mlp_gns': 'TabGNS-MLP', 'tabm_large': 'Large TabM (3×512, k=32)',
         'tabm_gns': 'TabGNS-TabM (shared mask)', 'tabm_gns_member': 'TabGNS-TabM (per-member masks)'}
BASE = {'mlp_gns': 'mlp_large', 'tabm_gns': 'tabm_large', 'tabm_gns_member': 'tabm_large'}
DATASETS = ['california', 'adult', 'otto']
PRIMARY = {'regression': ('rmse', False), 'classification': ('accuracy', True)}  # (metric, higher is better)


def load(results: Path) -> List[dict]:
  runs = []
  for p in sorted(results.glob('*/*/seed*.json')):
    r = json.loads(p.read_text())
    if 'error' in r:
      print(f'{p}: run failed:\n{r["error"]}')
      continue
    runs.append(r)
  return runs


def ms(xs: List[float], digits: int) -> str:
  if not xs:
    return '–'
  if len(xs) == 1:
    return f'{xs[0]:.{digits}f}'
  return f'{np.mean(xs):.{digits}f} ± {np.std(xs, ddof=1):.{digits}f}'


def fmt_int(x: float) -> str:
  return f'{x:,.0f}'


def paired(a: Dict[int, float], b: Dict[int, float]) -> Optional[tuple]:
  """Mean and per-seed values of a - b over the seeds both have."""
  seeds = sorted(set(a) & set(b))
  if not seeds:
    return None
  d = [a[s] - b[s] for s in seeds]
  return float(np.mean(d)), d


def summarise(runs: List[dict], out: Path) -> str:
  by = defaultdict(dict)  # (dataset, method) -> seed -> run
  for r in runs:
    by[(r['dataset'], r['method'])][r['seed']] = r
  lines = ['# TabGNS on TabM: results', '',
           'Generated by `python -m experiments.tabm_gns.report`. Mean ± sample std over seeds; '
           '"params" = all trainable parameters (TabM: shared weights + the k members\' adapters, biases '
           'and heads), "hidden" = hidden-to-hidden weights only (the paper\'s count), "size" = params '
           'relative to the Large model of the same backbone. RMSE for California is in units of '
           'log(1 + price / $100k), as the dataset ships on OpenML.', '']
  for ds in DATASETS:
    present = [m for m in METHODS if (ds, m) in by]
    if not present:
      continue
    task = next(iter(by[(ds, present[0])].values()))['task']
    metric, higher = PRIMARY[task]
    dig = 2 if metric == 'accuracy' else 4
    lines += [f'## {ds} ({task}, test {metric}, {"higher" if higher else "lower"} is better)', '',
              f'| method | seeds | test {metric} | ' + ('test log-loss | ' if task == 'classification' else '')
              + 'widths (per seed) | params | hidden | size vs Large |',
              '|---|---|---|' + ('---|' if task == 'classification' else '') + '---|---|---|---|']
    for m in present:
      rs = by[(ds, m)]
      vals = [r['metrics']['test'][metric] for r in rs.values()]
      base = by.get((ds, BASE.get(m, m)), {})
      sizes = [r['params']['full'] / base[s]['params']['full'] * 100 for s, r in rs.items() if s in base]
      row = f'| {LABEL[m]} | {len(rs)} | {ms(vals, dig)} | '
      if task == 'classification':
        row += ms([r['metrics']['test']['logloss'] for r in rs.values()], 4) + ' | '
      row += (' '.join(str(r['widths']) for _, r in sorted(rs.items())) + ' | '
              + fmt_int(np.mean([r['params']['full'] for r in rs.values()])) + ' | '
              + fmt_int(np.mean([r['params']['hidden'] for r in rs.values()])) + ' | '
              + (f'{np.mean(sizes):.1f}%' if sizes else '–') + ' |')
      lines.append(row)
    lines.append('')

    # Paired differences vs. the same backbone's Large model, and the warm-start / scratch decomposition.
    lines += [f'Paired differences in test {metric} (method − Large model of the same backbone, same seed):', '']
    for m in ('mlp_gns', 'tabm_gns', 'tabm_gns_member'):
      if (ds, m) not in by or (ds, BASE[m]) not in by:
        continue
      a = {s: r['metrics']['test'][metric] for s, r in by[(ds, m)].items()}
      b = {s: r['metrics']['test'][metric] for s, r in by[(ds, BASE[m])].items()}
      p = paired(a, b)
      if p:
        better = sum((d > 0) == higher and d != 0 for d in p[1])
        lines.append(f'- {LABEL[m]}: {p[0]:+.{dig}f} (per seed: {", ".join(f"{d:+.{dig}f}" for d in p[1])}; '
                     f'better than Large in {better}/{len(p[1])})')
    lines.append('')
    rows = []
    for m in ('tabm_gns', 'tabm_gns_member'):
      rs = by.get((ds, m), {})
      if not rs:
        continue
      ext = [r['metrics_extracted']['test'][metric] for r in rs.values()]
      fin = [r['metrics']['test'][metric] for r in rs.values()]
      scr = [r['metrics_scratch']['test'][metric] for r in rs.values() if 'metrics_scratch' in r]
      ep = [r['search']['epochs'] for r in rs.values()]
      bep = [r['search']['best_epoch'] for r in rs.values()]
      fep = [r['finetune']['epochs'] for r in rs.values()]
      rows.append(f'| {LABEL[m]} | {ms(ext, dig)} | {ms(fin, dig)} | {ms(scr, dig)} | '
                  f'{ms(ep, 0)} (best {ms(bep, 0)}) | {ms(fep, 0)} |')
    if rows:
      lines += ['TabGNS-TabM stages (test ' + metric + '): extracted sub-network before fine-tuning, after '
                'warm-start fine-tuning (the method\'s result), and the same widths trained from scratch:', '',
                '| method | extracted | fine-tuned | scratch | search epochs | fine-tune epochs |',
                '|---|---|---|---|---|---|', *rows, '']
    base_rs = by.get((ds, 'tabm_large'), {})
    if base_rs:
      lines.append(f'Large TabM epochs: {ms([r["train"]["epochs"] for r in base_rs.values()], 0)}.')
      lines.append('')
  text = '\n'.join(lines)
  (out / 'summary.md').write_text(text)
  return text


def write_csv(runs: List[dict], out: Path) -> None:
  cols = ['dataset', 'method', 'seed', 'task', 'metric', 'test', 'valid', 'test_extracted', 'test_scratch',
          'widths', 'params_full', 'params_hidden', 'params_shared', 'search_epochs', 'search_best_epoch',
          'train_epochs', 'wall_time_s']
  with open(out / 'runs.csv', 'w', newline='') as f:
    w = csv.writer(f)
    w.writerow(cols)
    for r in sorted(runs, key=lambda r: (r['dataset'], METHODS.index(r['method']), r['seed'])):
      metric = PRIMARY[r['task']][0]
      w.writerow([r['dataset'], r['method'], r['seed'], r['task'], metric, r['metrics']['test'][metric],
                  r['metrics']['valid'][metric], r.get('metrics_extracted', {}).get('test', {}).get(metric, ''),
                  r.get('metrics_scratch', {}).get('test', {}).get(metric, ''), ' '.join(map(str, r['widths'])),
                  r['params']['full'], r['params']['hidden'], r['params']['shared'],
                  r.get('search', {}).get('epochs', ''), r.get('search', {}).get('best_epoch', ''),
                  (r.get('finetune') or r.get('train') or {}).get('epochs', ''), round(r['wall_time_s'])])


def figures(runs: List[dict], out: Path) -> None:
  import matplotlib
  matplotlib.use('Agg')
  import matplotlib.pyplot as plt
  fig_dir = out / 'figures'
  fig_dir.mkdir(exist_ok=True)
  colors = {'mlp_large': '#9aa5b1', 'mlp_gns': '#52606d', 'tabm_large': '#f0b429', 'tabm_gns': '#2680c2',
            'tabm_gns_member': '#d64545'}
  markers = {'mlp_large': 's', 'mlp_gns': 'o', 'tabm_large': 's', 'tabm_gns': 'o', 'tabm_gns_member': '^'}

  # 1. Test metric vs. parameter count.
  fig, axes = plt.subplots(1, len(DATASETS), figsize=(5 * len(DATASETS), 4))
  for ax, ds in zip(axes, DATASETS):
    rs = [r for r in runs if r['dataset'] == ds]
    if not rs:
      continue
    metric = PRIMARY[rs[0]['task']][0]
    for m in METHODS:
      pts = [(r['params']['full'], r['metrics']['test'][metric]) for r in rs if r['method'] == m]
      if pts:
        x, y = zip(*pts)
        ax.scatter(x, y, c=colors[m], marker=markers[m], label=LABEL[m], s=40, alpha=.85)
    ax.set_xscale('log')
    ax.set_xlabel('trainable parameters (log)')
    ax.set_ylabel(f'test {metric}')
    ax.set_title(ds)
    ax.grid(alpha=.3)
  axes[0].legend(fontsize=7, loc='best')
  fig.tight_layout()
  fig.savefig(fig_dir / 'metric_vs_params.png', dpi=130)
  plt.close(fig)

  # 2. Total width during the search (seed 0), TabGNS-MLP vs. TabGNS-TabM.
  fig, axes = plt.subplots(1, len(DATASETS), figsize=(5 * len(DATASETS), 3.6))
  for ax, ds in zip(axes, DATASETS):
    for m in ('mlp_gns', 'tabm_gns', 'tabm_gns_member'):
      for r in runs:
        if r['dataset'] == ds and r['method'] == m and r['seed'] == 0:
          h = r.get('search', {}).get('arch_history') or []
          if h:
            ax.plot(range(1, len(h) + 1), [sum(a) for a in h], c=colors[m], label=LABEL[m])
    ax.set_title(f'{ds} (seed 0)')
    ax.set_xlabel('search epoch')
    ax.set_ylabel('kept neurons (all layers)')
    ax.grid(alpha=.3)
  axes[0].legend(fontsize=7)
  fig.tight_layout()
  fig.savefig(fig_dir / 'width_during_search.png', dpi=130)
  plt.close(fig)


def main() -> None:
  ap = argparse.ArgumentParser()
  ap.add_argument('--results', default='results/tabm_gns')
  args = ap.parse_args()
  out = Path(args.results)
  runs = load(out)
  print(summarise(runs, out))
  write_csv(runs, out)
  figures(runs, out)


if __name__ == '__main__':
  main()
